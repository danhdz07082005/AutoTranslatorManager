import os
from unittest.mock import MagicMock
from atm.config.schema import GameProfile
from atm.core.deployment.game_deployer import GameDeployer

def test_deployer_preserves_and_restores_user_config(tmp_path):
    game_dir = tmp_path / 'UnityGame'
    game_dir.mkdir()
    exe_path = game_dir / 'Game.exe'
    exe_path.touch()

    bepinex_config = game_dir / 'BepInEx' / 'config'
    bepinex_config.mkdir(parents=True)
    ini_file = bepinex_config / 'AutoTranslatorConfig.ini'

    original_content = "[Service]\nUnaffectedOpt=1 2 3\n\n[Behaviour]\nMinDialogueChars=99\nCustomSetting=UserValue\n"
    ini_file.write_text(original_content, encoding='utf-8')

    profile = GameProfile(
        game_name='UnityGame',
        exe_path=str(exe_path),
        engine='Unity Mono',
        translator='google',
        input_lang='ja',
        output_lang='vi'
    )

    deployer = GameDeployer()
    deployer.monitor = MagicMock()
    deployer.monitor.start_and_monitor.return_value = True

    deployer.deploy_and_launch(profile, payload_dir='')

    backup_file = str(ini_file) + '.atm_backup'
    assert os.path.exists(backup_file)

    merged_content = ini_file.read_text(encoding='utf-8')
    assert 'Endpoint=CustomTranslate' in merged_content
    assert 'MinDialogueChars=99' in merged_content
    assert 'CustomSetting=UserValue' in merged_content

    deployer._on_game_exited()

    assert not os.path.exists(backup_file)
    assert ini_file.exists()
    restored_content = ini_file.read_text(encoding='utf-8')
    assert restored_content == original_content

